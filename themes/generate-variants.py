#!/usr/bin/env python3
"""Generate the Neon Alley and Vending Glow themes from tokyo-snow-color-theme.json.

Edit only tokyo-snow-color-theme.json (the lamplit-glow palette), then run:

    python3 themes/generate-variants.py

Every palette colour in it is swapped for the variant's colour of the same name,
keeping any alpha suffix (#e1b56833 -> #f2aa4c33). The palettes are the
tokyo-snow.theme variants from gaddo-arch. With --check it writes nothing and
exits 1 if a generated file is out of date (CI runs this).
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASE = HERE / "tokyo-snow-color-theme.json"

NAMES = ["night", "shadow", "slate", "dim", "snow", "brick", "neon", "ember",
         "amber", "gold", "sage", "moss", "pine"]

PALETTES = {
    "lamplit-glow": ["#1c1c1a", "#2a2a28", "#3a3933", "#7d7860", "#f1e4b5", "#96402e", "#d5583d",
                     "#db814c", "#e1b568", "#ecd08f", "#c4c88e", "#a6d46c", "#6fc28a"],
    "neon-alley":   ["#1a1a17", "#282823", "#3a382f", "#807a5c", "#f3e6b6", "#a8341f", "#e8492b",
                     "#f07f3c", "#f2aa4c", "#f4cc72", "#c9d48a", "#a9c46f", "#7fae6a"],
    "vending-glow": ["#161613", "#24241f", "#36342b", "#868063", "#fff0c2", "#b8321c", "#ff4b2b",
                     "#ff8a3d", "#ffb547", "#ffd56b", "#d0e08a", "#a6d46c", "#6fc28a"],
}

VARIANTS = {
    "neon-alley": ("Tokyo Snow Neon Alley", "reds and oranges pushed to the sign glow; bold"),
    "vending-glow": ("Tokyo Snow Vending Glow", "near-full saturation, deepest backgrounds; loudest"),
}


def render(variant: str) -> str:
    base = dict(zip(PALETTES["lamplit-glow"], PALETTES[variant]))
    src = BASE.read_text()

    def swap(m: re.Match) -> str:
        hex6, alpha = m.group(1).lower(), m.group(2) or ""
        if hex6 == "#000000":
            return m.group(0)
        if hex6 not in base:
            sys.exit(f"{BASE.name}: {m.group(0)} is not a tokyo-snow palette colour")
        return base[hex6] + alpha

    out = re.sub(r"(#[0-9a-fA-F]{6})([0-9a-fA-F]{2})?\b", swap, src)
    label, blurb = VARIANTS[variant]
    out = out.replace("// tokyo-snow (lamplit-glow) — palette sampled from a snowy Tokyo alley at night",
                      f"// tokyo-snow ({variant}) — {blurb}\n"
                      f"  // GENERATED by generate-variants.py from tokyo-snow-color-theme.json; do not edit", 1)
    out = out.replace('"name": "Tokyo Snow",', f'"name": "{label}",', 1)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for variant in VARIANTS:
        path = HERE / f"tokyo-snow-{variant}-color-theme.json"
        text = render(variant)
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.name)
        else:
            path.write_text(text)
            print(f"wrote {path.name}")
    if stale:
        print("out of date, run python3 themes/generate-variants.py: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
